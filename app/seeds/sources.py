def seed_sources(session: Session) -> int:
    created = 0
    for s_data in SEEDED_SOURCES:
        existing = session.get(Source, s_data["id"])
        if not existing:
            source = Source(**s_data)
            session.add(source)
            created += 1
    session.commit()
    return created
